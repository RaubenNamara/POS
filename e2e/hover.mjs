import { chromium } from 'playwright'
const b = await chromium.launch({ executablePath: 'C:/Users/hp/AppData/Local/ms-playwright/chromium-1243/chrome-win64/chrome.exe' })
const p = await b.newPage({ viewport: { width: 1920, height: 960 } })
await p.goto('http://127.0.0.1:8000/')
await p.getByText('Top Deals').first().waitFor()
await p.mouse.wheel(0, 420)
await p.waitForTimeout(400)
const card = p.locator('article').nth(2)
await card.hover()
await p.waitForTimeout(300)
await p.screenshot({ path: process.argv[2] })
const before = await p.locator('header a[aria-label=Cart]').innerText()
await card.getByRole('button', { name: /Add .* to cart/ }).click()
await p.waitForTimeout(300)
console.log('cart badge before/after:', JSON.stringify(before), JSON.stringify(await p.locator('header a[aria-label=Cart]').innerText()))
const t = await b.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true })
await t.goto('http://127.0.0.1:8000/')
await t.getByText('Top Deals').first().waitFor()
console.log('visible on phone:', await t.locator('.quick-add').first().isVisible())
await b.close()
